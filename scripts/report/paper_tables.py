"""Write the paper's groundwater table from the committed adjudication record, so no
number in it is typed by hand: paper/sections/groundwater_tables.tex. Claims are labelled
in plain words; their pre-registered wording is in docs/predictions*.md.
"""
from __future__ import annotations

import json

from report.common import REPO_ROOT

RESULTS = REPO_ROOT / "results"
SECTIONS = REPO_ROOT / "paper" / "sections"
NAN = float("nan")

GROUNDWATER = {
    "G-1": "Error below 1\\%",
    "G-2": "Beats a classical network of the same size ($\\ge1.3\\times$)",
    "G-3": "Beats the same circuit with random frequencies ($\\ge1.5\\times$)",
    "G-4": "Gain over the MLP lies inside $\\Omega$ ($\\ge70\\%$)",
    "G-5": "Waterlogged length within 5\\% of the exact 713\\,m",
}
MODELS = (  # (adjudication family, label, parameters)
    ("q_serial_v2", "SMCD circuit, 8 copies", "91"),
    ("q_random_v2", "same circuit, random frequencies", "91"),
    ("c_mlp_matched_v2", "MLP, same size", "91"),
    ("c_rff_matched_v2", "frequency-matched classical, same size", "83"),
    ("c_mlp", "MLP, large", "8{,}513"),
)


def _load(name):
    path = RESULTS / name
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def groundwater_tables() -> None:
    rec = _load("adjudication_groundwater_v2.json")
    if not rec:
        return
    fam = rec["families"]
    measured = {
        "G-1": f"{100 * fam['q_serial_v2']['median_rel_l2']:.2f}\\%",
        "G-2": f"{rec['G-2'].get('measured_ratio', NAN):.1f}$\\times$",
        "G-3": f"{rec['G-3'].get('measured_ratio', NAN):.1f}$\\times$",
        "G-4": f"{100 * rec['G-4'].get('overlap_fraction', NAN):.1f}\\%",
        "G-5": f"{rec['G-5'].get('median_waterlogged_m', NAN):.0f}\\,m",
    }
    claims = "\n".join(f"  {GROUNDWATER[g]} & {measured[g]} \\\\" for g in GROUNDWATER
                       if rec[g].get("verdict") == "CONFIRMED")
    rows = "\n".join(f"  {label} & {size} & {100 * fam[f]['median_rel_l2']:.2f}\\% & "
                     f"{fam[f]['median_waterlogged_m']:.0f} \\\\" for f, label, size in MODELS if f in fam)
    body = (
        "\\begin{table}[htbp]\n  \\centering\n  \\small\n  \\begin{tabular}{lr}\n  \\toprule\n"
        "  Pre-registered claim, held on all five seeds & Measured \\\\\n  \\midrule\n" + claims +
        "\n  \\bottomrule\n  \\end{tabular}\\\\[8pt]\n"
        "  \\begin{tabular}{lrrr}\n  \\toprule\n"
        "  Model & parameters & median error & waterlogged (m) \\\\\n  \\midrule\n" + rows +
        "\n  \\bottomrule\n  \\end{tabular}\n"
        "  \\caption{Groundwater, held-out seeds 10--14: the pre-registered claims for the SMCD\n"
        "    circuit with eight copies (top) and every model's median relative $L^2$ error and\n"
        f"    waterlogged length (bottom). Exact waterlogged length: {rec['exact_waterlogged_m']:.0f}\\,m.}}\n"
        "  \\label{tab:gw}\n\\end{table}\n")
    (SECTIONS / "groundwater_tables.tex").write_text(
        "% Generated by scripts/report/paper_tables.py from results/adjudication_groundwater_v2.json.\n" + body,
        encoding="utf-8", newline="\n")


if __name__ == "__main__":
    groundwater_tables()
